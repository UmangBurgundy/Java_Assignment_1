public class PrimitiveDataTypes {
    public static void main(String[] args) {
        byte b = 10;
        short s = 100;
        int i = 1000;
        long l = 10000L;
        float f = 10.5f;
        double d = 99.99;
        char c = 'A';
        boolean flag = true;

        System.out.println("byte: " + b + ", int: " + i + ", double: " + d + ", char: " + c + ", boolean: " + flag);
    }
}
