public class S03_Q35_MavenPlugins {

    public static void main(String[] args) {
        System.out.println("Purpose of Maven Plugins:");
        System.out.println("Plugins extend Maven's build capabilities by executing goals during build phases.");
        System.out.println();
        System.out.println("Common Maven Plugins:");
        System.out.println("1. maven-compiler-plugin  - Compiles Java source code");
        System.out.println("2. maven-surefire-plugin  - Runs unit tests");
        System.out.println("3. maven-jar-plugin       - Creates JAR files");
        System.out.println("4. maven-war-plugin       - Creates WAR files");
        System.out.println("5. maven-shade-plugin     - Creates uber/fat JARs");
        System.out.println("6. maven-deploy-plugin    - Deploys to remote repository");
        System.out.println("7. maven-install-plugin   - Installs to local repository");
        System.out.println("8. maven-clean-plugin     - Cleans build output");
        System.out.println("9. maven-resources-plugin - Copies resources to output");
        System.out.println("10. maven-site-plugin     - Generates project documentation");
    }
}
